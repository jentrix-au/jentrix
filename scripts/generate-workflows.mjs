/** Materialize complete provider entrypoints; no runtime shared-file loading. */
import { readFileSync, writeFileSync, realpathSync } from "node:fs";
import { resolve, join } from "node:path";
import { fileURLToPath } from "node:url";

export const WORKFLOWS = [
  "connect",
  "align",
  "plan",
  "checkpoint",
  "review",
  "status",
  "end",
];
export const PROVIDERS = ["claude", "codex"];
const root = fileURLToPath(new URL("../", import.meta.url));
const source = join(root, "plugins/workflows");

export function workflowPath(
  provider,
  name,
  packageRoot = join(root, "plugins", provider),
) {
  if (!PROVIDERS.includes(provider) || !WORKFLOWS.includes(name))
    throw new Error("Unknown workflow entrypoint");
  return provider === "claude"
    ? join(packageRoot, "commands", `jentrix-${name}.md`)
    : join(
        packageRoot,
        "plugins/jentrix/skills",
        `jentrix-${name}`,
        "SKILL.md",
      );
}

export function renderWorkflow(provider, name) {
  workflowPath(provider, name); // validate the two finite names before reading
  const metadata = JSON.parse(
    readFileSync(join(source, "entrypoints.json"), "utf8"),
  );
  const read = (file) => readFileSync(join(source, file), "utf8").trim();
  const content = [
    read(`${provider}-entry.md`),
    read(`${name}.md`),
    read("common.md"),
  ].join("\n\n");
  const body = content
    .replaceAll("{{provider}}", provider)
    .replaceAll("{{prefix}}", provider === "claude" ? "/" : "$");
  if (/\{\{\w+\}\}/.test(body)) throw new Error("Unexpanded workflow variable");
  return `---\n${metadata[provider][name]}\n---\n<!-- Generated from plugins/workflows in jentrix-au/jentrix. Run pnpm gen:workflows; do not edit this file. -->\n\n${body}\n`;
}

export function generateWorkflows({ check = false } = {}) {
  for (const provider of PROVIDERS)
    for (const name of WORKFLOWS) {
      const file = workflowPath(provider, name);
      const expected = renderWorkflow(provider, name);
      const actual = readFileSync(file, "utf8");
      if (actual === expected) continue;
      if (check) throw new Error(`Stale ${file}; run pnpm gen:workflows`);
      writeFileSync(file, expected);
    }
}

if (
  process.argv[1] &&
  realpathSync(resolve(process.argv[1])) ===
    realpathSync(fileURLToPath(import.meta.url))
) {
  generateWorkflows({ check: process.argv.includes("--check") });
}
