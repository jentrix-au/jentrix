/**
 * Materialize complete provider entrypoints; no runtime shared-file loading.
 *
 * The finite host and workflow sets come from ONE registry
 * (`plugins/registry.json`, plugin-sync G01): an ENROLLED host is generated
 * and packed; a PLANNED host is listed there so every impact record must
 * account for it, but nothing is rendered for it until its adapter, package
 * and resources enroll it atomically (S3/S4). Adding a host anywhere else is
 * what `pnpm check:plugin-sync` exists to refuse.
 */
import { mkdirSync, readFileSync, writeFileSync, realpathSync } from "node:fs";
import { dirname, resolve, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("../", import.meta.url));
const source = join(root, "plugins/workflows");

/** The registry, read once per process; tests pass their own root. */
export function readRegistry(repoRoot = root) {
  return JSON.parse(
    readFileSync(join(repoRoot, "plugins/registry.json"), "utf8"),
  );
}

const registry = readRegistry();

export const WORKFLOWS = registry.workflows;
/** Enrolled hosts only — the ones with generated entrypoints and packages. */
export const PROVIDERS = Object.entries(registry.hosts)
  .filter(([, host]) => host.status === "enrolled")
  .map(([name]) => name);
/** Every official host, planned included (the all-host matrix). */
export const OFFICIAL_HOSTS = Object.keys(registry.hosts);

export function workflowPath(
  provider,
  name,
  packageRoot = join(root, registry.hosts[provider]?.packageDir ?? ""),
) {
  const host = registry.hosts[provider];
  if (!host || host.status !== "enrolled" || !WORKFLOWS.includes(name))
    throw new Error("Unknown workflow entrypoint");
  return join(packageRoot, host.workflowPath.replaceAll("{name}", name));
}

export function renderWorkflow(provider, name) {
  workflowPath(provider, name); // validate the two finite names before reading
  const host = registry.hosts[provider];
  const metadata = JSON.parse(
    readFileSync(join(source, "entrypoints.json"), "utf8"),
  );
  const read = (file) => readFileSync(join(source, file), "utf8").trim();
  const content = [
    read(`${provider}-entry.md`),
    read(`${name}.md`),
    read("common.md"),
  ].join("\n\n");
  const body = content
    .replaceAll("{{provider}}", provider)
    .replaceAll("{{prefix}}", host.prefix);
  if (/\{\{\w+\}\}/.test(body)) throw new Error("Unexpanded workflow variable");
  return `---\n${metadata[provider][name]}\n---\n<!-- Generated from plugins/workflows in jentrix-au/jentrix. Run pnpm gen:workflows; do not edit this file. -->\n\n${body}\n`;
}

export function generateWorkflows({ check = false } = {}) {
  for (const provider of PROVIDERS)
    for (const name of WORKFLOWS) {
      const file = workflowPath(provider, name);
      const expected = renderWorkflow(provider, name);
      // A host enrolled for the first time (M2) has no generated file yet:
      // missing is stale, never a crash.
      let actual = null;
      try {
        actual = readFileSync(file, "utf8");
      } catch {
        actual = null;
      }
      if (actual === expected) continue;
      if (check) throw new Error(`Stale ${file}; run pnpm gen:workflows`);
      mkdirSync(dirname(file), { recursive: true });
      writeFileSync(file, expected);
    }
}

if (
  process.argv[1] &&
  realpathSync(resolve(process.argv[1])) ===
    realpathSync(fileURLToPath(import.meta.url))
) {
  generateWorkflows({ check: process.argv.includes("--check") });
}
